// Generates Supabase SQL migrations + an entity->table map from the Base44
// entity definitions in base44/entities/*.jsonc.
//
//   node scripts/generate-schema.mjs
//
// Outputs (overwritten each run):
//   supabase/migrations/20250101000000_schema.sql
//   supabase/migrations/20250101000001_rls.sql
//   supabase/entity_map.json
//
// The generated SQL is committed to the repo so you don't have to run this,
// but re-run it whenever you change base44/entities/*.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const ENTITIES_DIR = path.join(ROOT, 'base44', 'entities');
const MIGRATIONS_DIR = path.join(ROOT, 'supabase', 'migrations');

// ---- helpers ---------------------------------------------------------------

// Tolerant JSONC parse: strip // line and /* */ block comments.
function parseJsonc(text) {
  const noBlock = text.replace(/\/\*[\s\S]*?\*\//g, '');
  const noLine = noBlock.replace(/(^|[^:])\/\/.*$/gm, '$1');
  return JSON.parse(noLine);
}

function snake(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1_$2')
    .toLowerCase();
}

// Entity name -> Postgres table name. `User` is special: it maps to `profiles`
// which is linked to Supabase auth.users.
function tableFor(name) {
  if (name === 'User') return 'profiles';
  return snake(name);
}

const STANDARD_COLS = new Set(['id', 'created_date', 'updated_date', 'created_by_id', 'created_by']);

function pgType(prop) {
  switch (prop.type) {
    case 'number': return 'numeric';
    case 'boolean': return 'boolean';
    case 'object': return 'jsonb';
    case 'array': return 'jsonb';
    case 'string':
    default: return 'text';
  }
}

function sqlLiteral(v) {
  return `'${String(v).replace(/'/g, "''")}'`;
}

function pgDefault(prop) {
  if (prop.default === undefined || prop.default === null) return '';
  switch (prop.type) {
    case 'boolean': return ` default ${prop.default ? 'true' : 'false'}`;
    case 'number': return ` default ${Number(prop.default)}`;
    case 'array':
    case 'object': return ` default ${sqlLiteral(JSON.stringify(prop.default))}::jsonb`;
    default: return ` default ${sqlLiteral(prop.default)}`;
  }
}

// ---- RLS translation -------------------------------------------------------
// Values may be literals or templates:
//   {{user.id}}                 -> the current auth user id (text)
//   {{user.data.<field>}}       -> the current user's profile.<field>
function translateValue(v) {
  if (typeof v !== 'string') return sqlLiteral(v);
  if (v === '{{user.id}}') return 'auth.uid()::text';
  const m = v.match(/^\{\{user\.data\.([a-zA-Z0-9_]+)\}\}$/);
  if (m) return `(public.current_profile()).${m[1]}`;
  return sqlLiteral(v);
}

// A rule is one of:
//   null                         -> always allow (public)
//   { $or:  [rule, ...] }
//   { $and: [rule, ...] }
//   { user_condition: { field: value, ... } }  -> checks the CURRENT USER
//   { <recordField>: value, ... }               -> checks the ROW
// A leading `data.` on a key refers to a custom field (strip it).
function translateRule(rule) {
  if (rule === null || rule === undefined) return 'true';
  if (Array.isArray(rule.$or)) {
    return '(' + rule.$or.map(translateRule).join(' or ') + ')';
  }
  if (Array.isArray(rule.$and)) {
    return '(' + rule.$and.map(translateRule).join(' and ') + ')';
  }
  if (rule.user_condition) {
    const parts = Object.entries(rule.user_condition).map(([k, v]) => {
      const field = k.replace(/^data\./, '');
      return `(public.current_profile()).${field} = ${translateValue(v)}`;
    });
    return '(' + parts.join(' and ') + ')';
  }
  const parts = Object.entries(rule).map(([k, v]) => {
    const col = k.replace(/^data\./, '');
    return `${col} = ${translateValue(v)}`;
  });
  return '(' + (parts.length ? parts.join(' and ') : 'true') + ')';
}

// ---- load entities ---------------------------------------------------------
const files = fs.readdirSync(ENTITIES_DIR).filter((f) => f.endsWith('.jsonc') || f.endsWith('.json'));
const entities = files.map((f) => parseJsonc(fs.readFileSync(path.join(ENTITIES_DIR, f), 'utf8')));
entities.sort((a, b) => a.name.localeCompare(b.name));

const entityMap = {};
for (const e of entities) entityMap[e.name] = tableFor(e.name);

// ---- schema.sql ------------------------------------------------------------
const schema = [];
schema.push('-- AUTO-GENERATED by scripts/generate-schema.mjs — do not edit by hand.');
schema.push('-- Tables mirror base44/entities/*. Standard Base44 columns are added to every table.');
schema.push('');
schema.push('create extension if not exists pgcrypto;');
schema.push('');
schema.push(`-- Keep updated_date fresh on every UPDATE.
create or replace function public.set_updated_date()
returns trigger language plpgsql as $$
begin
  new.updated_date = now();
  return new;
end $$;`);
schema.push('');

// profiles (User) is created specially: PK references auth.users.
const userEntity = entities.find((e) => e.name === 'User');
const userProps = (userEntity && userEntity.properties) || {};
schema.push('-- profiles: the Base44 `User` entity, linked to Supabase auth.users.');
const profileCols = [
  'id uuid primary key references auth.users(id) on delete cascade',
  'base44_id text unique',
  'email text',
  'full_name text',
];
for (const [name, prop] of Object.entries(userProps)) {
  if (['email', 'full_name', 'id'].includes(name)) continue;
  profileCols.push(`${name} ${pgType(prop)}${pgDefault(prop)}`);
}
profileCols.push('created_date timestamptz not null default now()');
profileCols.push('updated_date timestamptz not null default now()');
profileCols.push('created_by_id text');
profileCols.push('created_by text');
schema.push(`create table if not exists public.profiles (\n  ${profileCols.join(',\n  ')}\n);`);
schema.push('create index if not exists profiles_community_id_idx on public.profiles(community_id);');
schema.push('create index if not exists profiles_organization_id_idx on public.profiles(organization_id);');
schema.push('create trigger profiles_set_updated before update on public.profiles for each row execute function public.set_updated_date();');
schema.push('');
schema.push(`-- Auto-create a profile row when a new auth user signs up.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name'))
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();`);
schema.push('');

for (const e of entities) {
  if (e.name === 'User') continue;
  const table = tableFor(e.name);
  const cols = [
    'id text primary key default gen_random_uuid()::text',
    'created_date timestamptz not null default now()',
    'updated_date timestamptz not null default now()',
    'created_by_id text',
    'created_by text',
  ];
  const idIndexCols = [];
  for (const [name, prop] of Object.entries(e.properties || {})) {
    if (STANDARD_COLS.has(name)) continue;
    cols.push(`${name} ${pgType(prop)}${pgDefault(prop)}`);
    if (name.endsWith('_id') || name === 'join_code') idIndexCols.push(name);
  }
  schema.push(`-- ${e.name}`);
  schema.push(`create table if not exists public.${table} (\n  ${cols.join(',\n  ')}\n);`);
  for (const c of idIndexCols) {
    schema.push(`create index if not exists ${table}_${c}_idx on public.${table}(${c});`);
  }
  schema.push(`create index if not exists ${table}_created_date_idx on public.${table}(created_date);`);
  schema.push(`create trigger ${table}_set_updated before update on public.${table} for each row execute function public.set_updated_date();`);
  schema.push('');
}

// ---- rls.sql ---------------------------------------------------------------
const rls = [];
rls.push('-- AUTO-GENERATED by scripts/generate-schema.mjs — do not edit by hand.');
rls.push('-- Row-Level Security translated from each entity\'s `rls` block.');
rls.push('');
rls.push(`-- Returns the current user's profile row. SECURITY DEFINER so it can be
-- referenced inside other tables' policies without recursing through RLS.
create or replace function public.current_profile()
returns public.profiles language sql stable security definer set search_path = public as $$
  select * from public.profiles where id = auth.uid()
$$;`);
rls.push('');
rls.push('-- profiles (User): managed access. Authenticated users may read profiles');
rls.push('-- (needed for community/board/homeowner listings); users update only their own.');
rls.push('alter table public.profiles enable row level security;');
rls.push(`create policy profiles_select on public.profiles for select using (auth.uid() is not null);`);
rls.push(`create policy profiles_update_self on public.profiles for update using (id = auth.uid()) with check (id = auth.uid());`);
rls.push('');

for (const e of entities) {
  if (e.name === 'User') continue;
  const table = tableFor(e.name);
  const r = e.rls || { create: null, read: null, update: null, delete: null };
  rls.push(`-- ${e.name}`);
  rls.push(`alter table public.${table} enable row level security;`);
  const readExpr = translateRule(r.read);
  const createExpr = translateRule(r.create);
  const updateExpr = translateRule(r.update);
  const deleteExpr = translateRule(r.delete);
  rls.push(`create policy ${table}_select on public.${table} for select using (${readExpr});`);
  rls.push(`create policy ${table}_insert on public.${table} for insert with check (${createExpr});`);
  rls.push(`create policy ${table}_update on public.${table} for update using (${updateExpr}) with check (${updateExpr});`);
  rls.push(`create policy ${table}_delete on public.${table} for delete using (${deleteExpr});`);
  rls.push('');
}

// ---- write -----------------------------------------------------------------
fs.mkdirSync(MIGRATIONS_DIR, { recursive: true });
fs.writeFileSync(path.join(MIGRATIONS_DIR, '20250101000000_schema.sql'), schema.join('\n'));
fs.writeFileSync(path.join(MIGRATIONS_DIR, '20250101000001_rls.sql'), rls.join('\n'));
fs.writeFileSync(path.join(ROOT, 'supabase', 'entity_map.json'), JSON.stringify(entityMap, null, 2) + '\n');

// A JS copy the frontend shim imports so entity->table naming has one source of truth.
const jsMap = `// AUTO-GENERATED by scripts/generate-schema.mjs — do not edit by hand.
// Maps Base44 entity names to their Postgres table names.
export const ENTITY_TABLES = ${JSON.stringify(entityMap, null, 2)};
`;
fs.mkdirSync(path.join(ROOT, 'src', 'api'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src', 'api', 'entityTables.js'), jsMap);

// A TypeScript copy the Deno edge-function compat shim imports, so entity->table
// naming stays in sync across frontend and backend.
const tsMap = `// AUTO-GENERATED by scripts/generate-schema.mjs — do not edit by hand.
// Maps Base44 entity names to their Postgres table names.
export const ENTITY_TABLES: Record<string, string> = ${JSON.stringify(entityMap, null, 2)};
`;
const SHARED_DIR = path.join(ROOT, 'supabase', 'functions', '_shared');
fs.mkdirSync(SHARED_DIR, { recursive: true });
fs.writeFileSync(path.join(SHARED_DIR, 'entity-map.ts'), tsMap);

console.log(`Generated schema + RLS for ${entities.length} entities.`);
console.log('  supabase/migrations/20250101000000_schema.sql');
console.log('  supabase/migrations/20250101000001_rls.sql');
console.log('  supabase/entity_map.json');
console.log('  src/api/entityTables.js');
console.log('  supabase/functions/_shared/entity-map.ts');
